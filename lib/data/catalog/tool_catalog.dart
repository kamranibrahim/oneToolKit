  static ToolModel? byId(String id) {
    try {
      return all.firstWhere((t) => t.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<ToolModel> byCategory(ToolCategory category) =>
      all.where((t) => t.category == category).toList();

  static List<ToolModel> search(String query) =>
      all.where((t) => t.matches(query)).toList();

  static List<ToolModel> get recommended =>
      all.where((t) => t.isRecommended && t.isAvailable).toList();

  static List<ToolModel> get trending =>
      all.where((t) => t.isTrending).toList();

  static List<ToolModel> get available =>
      all.where((t) => t.isAvailable).toList();
}
